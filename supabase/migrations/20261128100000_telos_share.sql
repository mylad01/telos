-- Phase D of docs/FEATURES.md: share one list with another account by invite
-- code. A share is a row in `list_shares`; accepting it binds `member_id` and
-- the task policies below then treat that member as a guest in the owner's list.
--
-- Run in the Supabase SQL editor after 20261127090000_telos_task_structure.sql.
-- Safe to run more than once: every object is created only when missing.

create table if not exists public.list_shares (
  id          uuid        primary key default gen_random_uuid(),
  -- The list name stays a plain string, exactly as `tasks.list` is. A share
  -- therefore covers the owner's rows with this name, past and future.
  owner_id    uuid        not null default auth.uid() references auth.users (id) on delete cascade,
  -- Null while the invite is pending; `telos_join_share` fills it in.
  member_id   uuid        references auth.users (id) on delete cascade,
  -- Generated by the app from an alphabet without 0/O/1/I, so it can be read
  -- aloud. One code binds one member; revoking deletes the row.
  invite_code text        not null unique check (invite_code ~ '^[A-HJ-NP-Z2-9]{8}$'),
  list        text        not null check (char_length(list) between 1 and 40),
  -- Display only: the owner's address at invite time. Never used for access.
  owner_email text        not null default '',
  role        text        not null default 'viewer' check (role in ('editor', 'viewer')),
  created_at  timestamptz not null default now(),
  -- An owner cannot accept their own invite; that would make the task policies
  -- ambiguous about which side is the guest.
  constraint list_shares_not_self check (member_id is distinct from owner_id)
);

create index if not exists list_shares_member_idx on public.list_shares (member_id);
create index if not exists list_shares_owner_list_idx on public.list_shares (owner_id, list);

alter table public.list_shares enable row level security;

-- Owners see and manage every invite they created, accepted or not.
drop policy if exists list_shares_owner on public.list_shares;
create policy list_shares_owner on public.list_shares
  for all
  to authenticated
  using (auth.uid() = owner_id)
  with check (auth.uid() = owner_id);

-- A member sees only the row that made them a member. Pending rows stay
-- invisible to everyone but the owner, so codes cannot be enumerated.
drop policy if exists list_shares_member on public.list_shares;
create policy list_shares_member on public.list_shares
  for select
  to authenticated
  using (auth.uid() = member_id);

revoke all on public.list_shares from anon;
grant select, insert, update, delete on public.list_shares to authenticated;

-- The join path. A pending invite is invisible to the caller, so a policy
-- cannot match it; a security-definer function can look it up and bind the
-- caller. It exposes only the list name, never the owner's id or email.
create or replace function public.telos_join_share(code text)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  share public.list_shares%rowtype;
  wanted text := upper(trim(coalesce(code, '')));
begin
  if auth.uid() is null then
    raise exception 'sign in first';
  end if;
  if wanted = '' then
    raise exception 'invite code required';
  end if;

  select * into share
    from public.list_shares
   where invite_code = wanted
     for update;

  if not found then
    raise exception 'invite not found';
  end if;
  if share.owner_id = auth.uid() then
    return share.list;
  end if;
  if share.member_id is not null and share.member_id <> auth.uid() then
    raise exception 'invite already used';
  end if;

  update public.list_shares
     set member_id = auth.uid()
   where id = share.id;

  return share.list;
end;
$$;

revoke all on function public.telos_join_share(text) from public;
grant execute on function public.telos_join_share(text) to authenticated;

-- Task access, layered on top of the owner-only `tasks_owner` policy from
-- 20261125100000_telos_tasks.sql. Policies are permissive, so these only ever
-- widen access; they never take the owner's own access away.
--
-- A member reads the owner's rows in the shared list name. In a shared list the
-- rows keep `user_id = owner_id`, so a guest's edits stay in one synced list.
drop policy if exists tasks_shared_select on public.tasks;
create policy tasks_shared_select on public.tasks
  for select
  to authenticated
  using (
    exists (
      select 1
        from public.list_shares s
       where s.list = tasks.list
         and s.owner_id = tasks.user_id
         and s.member_id = auth.uid()
    )
  );

-- Editors may add tasks to the shared list, and the new row must belong to the
-- owner (`s.owner_id = tasks.user_id`) or the owner would never see it.
drop policy if exists tasks_shared_insert on public.tasks;
create policy tasks_shared_insert on public.tasks
  for insert
  to authenticated
  with check (
    exists (
      select 1
        from public.list_shares s
       where s.list = tasks.list
         and s.member_id = auth.uid()
         and s.role = 'editor'
         and s.owner_id = tasks.user_id
    )
  );

-- Editors may update those rows, including the tombstone `deleted_at` the app
-- writes. The `with check` repeats the lookup against the new row values, so an
-- editor cannot move a task into a list they do not share.
drop policy if exists tasks_shared_update on public.tasks;
create policy tasks_shared_update on public.tasks
  for update
  to authenticated
  using (
    exists (
      select 1
        from public.list_shares s
       where s.list = tasks.list
         and s.member_id = auth.uid()
         and s.role = 'editor'
         and s.owner_id = tasks.user_id
    )
  )
  with check (
    exists (
      select 1
        from public.list_shares s
       where s.list = tasks.list
         and s.member_id = auth.uid()
         and s.role = 'editor'
         and s.owner_id = tasks.user_id
    )
  );

-- Viewers deliberately get no insert or update policy, and no member gets
-- delete: removing a row is an owner action (the app only writes tombstones).
